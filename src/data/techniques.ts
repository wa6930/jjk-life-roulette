/** 获取术式轮盘条目（根据状态过滤） */
export function getTechniqueWheelItems(tags: string[], phase: string) {
  return TECHNIQUES
    .filter(t => {
      if (t.minPhase === 'career' && phase !== 'career' && phase !== 'legend') return false
      if (t.requireTags && !t.requireTags.some(rt => tags.includes(rt))) return false
      if (t.excludeTags && t.excludeTags.some(et => tags.includes(et))) return false
      return true
    })
    .map(t => ({
      id: t.id,
      label: t.name,
      icon: t.icon,
      weight: t.weight,
    }))
}
